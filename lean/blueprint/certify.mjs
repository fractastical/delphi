#!/usr/bin/env node
// Generates a kernel-checkable certificate for one emitted blueprint:
//   node lean/blueprint/certify.mjs organism-design/examples/a-flying-fish.json
// Reads the blueprint and the pinned taxon statements (lean/blueprint/data/<name>.taxon.json, from
// fetch-taxon.mjs; the pinned sha256 must match the blueprint file, or this refuses), writes
//   lean/Delphi/Certificates/<Name>.lean   the graph and taxon data as Lean literals, and the theorems
//                                          `<name>_check` (by decide +kernel), `<name>_wellFormed`,
//                                          `<name>_counts` (distinct terms per level), `<name>_size`
//   lean/blueprint/certificates/<name>.json what the certificate pins and claims, for report.mjs and the records
// then compiles the Lean file. The generic theory is lean/Delphi/Blueprint.lean; nothing here is trusted:
// the kernel re-evaluates the checker on these literals. Regenerate whenever the blueprint is rebuilt.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const leanDir = path.resolve(here, '..');
const root = path.resolve(here, '../..');
const file = process.argv[2];
if (!file) { console.error('usage: node lean/blueprint/certify.mjs <blueprint.json>'); process.exit(2); }
const B = JSON.parse(fs.readFileSync(file, 'utf8'));
const name = path.basename(file, '.json');
const sha = crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex');
const dataFile = path.join(here, 'data', `${name}.taxon.json`);
if (!fs.existsSync(dataFile)) { console.error(`no pinned taxon data: run node lean/blueprint/fetch-taxon.mjs ${file}`); process.exit(2); }
const D = JSON.parse(fs.readFileSync(dataFile, 'utf8'));
if (D.blueprint.sha256 !== sha) { console.error(`pinned taxon data is for a different blueprint (sha256 ${D.blueprint.sha256.slice(0, 12)} vs ${sha.slice(0, 12)}); rerun fetch-taxon.mjs`); process.exit(2); }

// Node identity is the ontology term (IRI), not the placement: a term placed under several wholes is one node
// with several part_of edges. Root first, then the rest in IRI order, so the file is deterministic.
const LEVEL = { body: 0, organ_system: 1, organ: 2, tissue: 3, cell: 4 };
const rootNode = B.nodes.find(n => n.level === 'body' && n.parent === null);
if (!rootNode) throw new Error('no body root');
const iris = [rootNode.iri, ...[...new Set(B.nodes.map(n => n.iri))].filter(i => i !== rootNode.iri).sort()];
const idx = new Map(iris.map((i, k) => [i, k]));
const levelOf = new Map();
for (const n of B.nodes) {
  const l = LEVEL[n.level]; if (l === undefined) throw new Error('unknown level ' + n.level);
  if (levelOf.has(n.iri) && levelOf.get(n.iri) !== l) throw new Error(`term ${n.iri} placed at two levels`);
  levelOf.set(n.iri, l);
}
const levels = iris.map(i => levelOf.get(i));
const edgeSet = new Set();
for (const n of B.nodes) if (n.parent !== null) { if (n.relation !== 'part_of') throw new Error(`relation ${n.relation} on ${n.id}: only part_of is modelled`); if (!idx.has(n.parent)) throw new Error('parent not a node: ' + n.parent); edgeSet.add(`${idx.get(n.iri)},${idx.get(n.parent)}`); }
const edges = [...edgeSet].map(s => s.split(',').map(Number)).sort((a, b) => a[0] - b[0] || a[1] - b[1]);
const placements = B.nodes.filter(n => n.parent !== null).length;
const taxId = iri => Number(String(iri).replace(/^.*NCBITaxon_/, ''));
const neverIn = D.neverIn.filter(r => r.taxid !== null && idx.has(r.term)).map(r => [idx.get(r.term), r.taxid]);
const neverInNonNcbi = D.neverIn.filter(r => r.taxid === null).length;
const inTaxon = D.inTaxon.filter(r => idx.has(r.term)).map(r => [idx.get(r.term), r.taxid]);
const stated = [...new Set(B.nodes.filter(n => n.stated_in_taxon?.iri).map(n => `${idx.get(n.iri)},${taxId(n.stated_in_taxon.iri)}`))].map(s => s.split(',').map(Number));
const uniqPairs = a => [...new Set(a.map(p => p.join(',')))].map(s => s.split(',').map(Number)).sort((x, y) => x[0] - y[0] || x[1] - y[1]);
const counts = Object.fromEntries(Object.entries(LEVEL).map(([k, l]) => [k, levels.filter(x => x === l).length]));

const Name = name.split(/[^a-z0-9]+/i).filter(Boolean).map(w => w[0].toUpperCase() + w.slice(1)).join('');
const id = Name[0].toLowerCase() + Name.slice(1);
const pairs = a => '[' + a.map(([x, y]) => `(${x}, ${y})`).join(', ') + ']';
const lean = `import Delphi.Blueprint
/-!
GENERATED by lean/blueprint/certify.mjs from ${D.blueprint.file} (sha256 ${sha}, built ${B.built}) and
lean/blueprint/data/${name}.taxon.json (Ubergraph, ${D.queries.length} queries retrieved ${D.queries[0].retrieved} to ${D.queries[D.queries.length - 1].retrieved}). Do not edit; regenerate.
Nodes are distinct ontology terms (${iris.length}; index 0 is the body root ${rootNode.iri}), edges are the ${edges.length}
distinct part_of placements (${placements} placements in the file), levels body 0 / organ system 1 / organ 2 / tissue 3 / cell 4.
Taxon data: ${D.ancestors.length} ancestors of ${B.reading.taxon.term}, ${neverIn.length} never_in_taxon rows reachable from kept terms
(${neverInNonNcbi} with a non-NCBITaxon object, not representable and listed in the JSON certificate), ${inTaxon.length} in_taxon rows,
${stated.length} stated_in_taxon rows from the blueprint file.
-/

set_option maxRecDepth 1000000

namespace Delphi.Blueprint.Certificates

def ${id}Levels : List ℕ := [${levels.join(', ')}]

def ${id}Edges : List (ℕ × ℕ) := ${pairs(edges)}

/-- The blueprint graph of "${B.input.description}" (${B.reading.taxon.label}, ${B.reading.taxon.term}). -/
def ${id} : Graph ℕ := { nodes := List.range ${iris.length}, root := 0, level := fun i => ${id}Levels.getD i 0, partOf := ${id}Edges }

def ${id}Taxon : TaxonData ℕ ℕ :=
  { ancestors := [${D.ancestors.join(', ')}],
    neverIn := ${pairs(uniqPairs(neverIn))},
    inTaxon := ${pairs(uniqPairs(inTaxon))},
    stated := ${pairs(uniqPairs(stated))} }

/-- The checker accepts the data: the kernel evaluates \`check\` on the literals above. -/
theorem ${id}_check : check ${id} ${id}Taxon = true := by decide +kernel

/-- **The emitted structure is well-formed**: edges strictly down in level, closed, acyclic, every node reaches
the body root, no kept term excluded from the taxon and every cited taxon contains it. -/
theorem ${id}_wellFormed : WellFormed ${id} ${id}Taxon := wellFormed_of_check _ _ ${id}_check

/-- Nodes are distinct terms, counted once each. -/
theorem ${id}_nodup : ${id}.nodes.Nodup := List.nodup_range

/-- Distinct terms per level, as the organism thread's label must report them. -/
theorem ${id}_counts : ${id}.countLevel 0 = ${counts.body} ∧ ${id}.countLevel 1 = ${counts.organ_system} ∧ ${id}.countLevel 2 = ${counts.organ} ∧
    ${id}.countLevel 3 = ${counts.tissue} ∧ ${id}.countLevel 4 = ${counts.cell} := by decide +kernel

/-- Size of the certified graph. -/
theorem ${id}_size : ${id}.nodes.length = ${iris.length} ∧ ${id}.partOf.length = ${edges.length} := by decide +kernel

end Delphi.Blueprint.Certificates
`;
fs.mkdirSync(path.join(leanDir, 'Delphi/Certificates'), { recursive: true });
const leanFile = path.join(leanDir, 'Delphi/Certificates', `${Name}.lean`);
fs.writeFileSync(leanFile, lean);

// Compile the certificate file (the kernel does the checking).
const candidates = [process.env.ELAN_HOME, path.join(process.env.USERPROFILE || process.env.HOME || '', '.elan'), 'C:/Temp/elan'].filter(Boolean);
let bin = '';
for (const c of candidates) { const d = path.join(c, 'bin'); if (fs.existsSync(path.join(d, process.platform === 'win32' ? 'lake.exe' : 'lake'))) { bin = d; break; } }
const env = { ...process.env, PATH: (bin ? bin + path.delimiter : '') + process.env.PATH };
if (bin && !process.env.ELAN_HOME) env.ELAN_HOME = path.dirname(bin);
const t0 = Date.now();
const r = spawnSync('lake', ['env', 'lean', `Delphi/Certificates/${Name}.lean`], { cwd: leanDir, env, encoding: 'utf8', shell: process.platform === 'win32', maxBuffer: 64 * 1024 * 1024 });
const out = (r.stdout || '') + (r.stderr || '');
const ok = r.status === 0 && !/error:/.test(out);
const cert = {
  generated: new Date().toISOString(), tool: 'lean/blueprint/certify.mjs', name, leanModule: `lean/Delphi/Certificates/${Name}.lean`, theory: 'lean/Delphi/Blueprint.lean',
  blueprint: { file: D.blueprint.file, built: B.built, sha256: sha, description: B.input.description, taxon: B.reading.taxon },
  taxonData: { file: `lean/blueprint/data/${name}.taxon.json`, sha256: crypto.createHash('sha256').update(fs.readFileSync(dataFile)).digest('hex'), endpoint: D.queries[0].endpoint, queries: D.queries.length, retrieved: { first: D.queries[0].retrieved, last: D.queries[D.queries.length - 1].retrieved }, rows: { ancestors: D.ancestors.length, neverIn: neverIn.length, neverInNonNcbi, inTaxon: inTaxon.length, stated: stated.length } },
  graph: { distinctTerms: iris.length, placementsInFile: placements, distinctEdges: edges.length, multiPlacedTerms: iris.filter((_, k) => edges.filter(e => e[0] === k).length > 1).length, countsByLevelDistinct: counts, countsByLevelPlacements: Object.fromEntries(Object.keys(LEVEL).map(k => [k, B.nodes.filter(n => n.level === k).length])), fileCounts: B.counts },
  theorems: { check: `Delphi.Blueprint.Certificates.${id}_check`, wellFormed: `Delphi.Blueprint.Certificates.${id}_wellFormed`, nodup: `Delphi.Blueprint.Certificates.${id}_nodup`, counts: `Delphi.Blueprint.Certificates.${id}_counts`, size: `Delphi.Blueprint.Certificates.${id}_size` },
  compile: { ok, exit: r.status, seconds: +((Date.now() - t0) / 1000).toFixed(1), tail: out.trim().split(/\r?\n/).slice(-4) },
  kernelChecked: [
    'Every part_of edge goes from a strictly deeper level to a shallower one (Graph.LevelsDown), so the part_of relation is acyclic: no term is transitively part of itself (Graph.acyclic_of_levelsDown).',
    'The transitive closure of the stated edges is transitive and strictly decreases the level (Graph.transGen_trans, Graph.transGen_level_lt).',
    'Every edge joins two nodes of the graph and every node other than the body root has a whole, hence every node reaches the body root: no orphans (Graph.rooted_of).',
    'No never_in_taxon statement pinned from Ubergraph on a kept term, a superclass or a whole names a taxon containing the blueprint taxon; every in_taxon and stated_in_taxon statement names a containing taxon (TaxonData.Ok).',
    `Nodes are distinct terms (List.nodup_range) and the distinct counts per level are ${Object.entries(counts).map(([k, v]) => `${k} ${v}`).join(', ')}; the file holds ${placements} placements.`
  ],
  assumed: [
    'That Uberon and the Cell Ontology are correct and that Ubergraph served their part_of, subClassOf, never_in_taxon and in_taxon statements correctly and completely on the retrieval dates; the graph and the taxon rows are data whose hashes and queries are pinned here.',
    'That the five levels are the right notion of depth; the theorems use only that edges strictly decrease it.',
    `${neverInNonNcbi} never_in_taxon row(s) whose object is not an NCBITaxon term are not representable in the checker and are listed in the taxon data file, not checked.`,
    'Nothing about any organism: the certificate says the emitted structure is internally coherent under its own stated rules. It does not say the fish is real, that the anatomy is correct or complete, that any part was measured, or anything about a transition between forms.'
  ]
};
fs.mkdirSync(path.join(here, 'certificates'), { recursive: true });
fs.writeFileSync(path.join(here, 'certificates', `${name}.json`), JSON.stringify(cert, null, 1));
console.log(`${leanFile}: ${iris.length} terms, ${edges.length} edges (${placements} placements), taxon rows ${neverIn.length}/${inTaxon.length}/${stated.length}; compile ${ok ? 'ok' : 'FAILED'} in ${cert.compile.seconds}s`);
if (!ok) { console.log(out.trim().split(/\r?\n/).slice(0, 20).join('\n')); process.exit(1); }
