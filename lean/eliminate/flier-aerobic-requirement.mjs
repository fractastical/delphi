#!/usr/bin/env node
// What the aerobic bound asks of the HYPOTHETICAL flier F1 (physics/flier/spec.json): from
//   sustained_flight_requires / climb_le_aerobic (lean/Delphi/Flight.lean):  P_req + W c <= eta * E_O2 * Q * Ca
// the oxygen delivery Q * Ca the design must have is at least (P_req + W c) / (eta * E_O2). No cardiac output or
// arterial O2 content is sourced for any Exocoetidae, so the bound itself is cannot-evaluate; this file states the
// requirement the physiology must meet, computed from the physics thread's numbers, with every input named.
//   node lean/eliminate/flier-aerobic-requirement.mjs -> lean/eliminate/flier-aerobic-requirement.json
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../..');
const S = JSON.parse(fs.readFileSync(path.join(root, 'physics/flier/spec.json'), 'utf8'));
const eta = S.design.conversion_efficiency.value, E = S.sources.oxycaloric_J_per_ml_O2.value, mass = S.design.mass_kg.value, g = 9.80665, W = mass * g;
const rows = S.power_budget.P_req_table.filter(r => r.P_req_level_W !== null).map(r => {
  const climbW = r.P_req_climb_1_m_s_W, levelW = r.P_req_level_W;
  const o2 = mech => mech / (eta * E); // ml O2 per second
  return { v_m_s: r.v_m_s, P_req_level_W: levelW, P_req_climb_1_m_s_W: climbW, climb_term_W: +(W * 1).toFixed(4),
    metabolic_needed_level_W: +(levelW / eta).toFixed(3), metabolic_needed_climb_W: +(climbW / eta).toFixed(3),
    O2_needed_level_ml_per_s: +o2(levelW).toFixed(4), O2_needed_climb_ml_per_s: +o2(climbW).toFixed(4),
    O2_needed_climb_ml_per_min_per_kg: +(o2(climbW) * 60 / mass).toFixed(1) };
});
const out = {
  theorem: 'Delphi.climb_le_aerobic (and Delphi.sustained_flight_requires), lean/Delphi/Flight.lean', relation: 'P_req + W c <= eta * E_O2 * Q * Ca  =>  Q * Ca >= (P_req + W c) / (eta * E_O2)',
  inputs: { mass_kg: mass, weight_N: +W.toFixed(4), efficiency_eta: eta, efficiency_source: S.design.conversion_efficiency.reason, oxycaloric_J_per_ml_O2: E, oxycaloric_source: S.sources.oxycaloric_J_per_ml_O2.source, P_req_source: 'physics/flier/spec.json power_budget.P_req_table (the physics thread\'s simulator, measured polar of Park and Choi 2010)' },
  requirement: rows,
  physicsFigure: { metabolic_power_W_for_climb: S.power_budget.metabolic_power_W_for_climb, metabolic_W_per_kg_body: S.power_budget.metabolic_W_per_kg_body, note: 'the hub quoted 18.6 W metabolic for a 1 m/s climb at 0.06 kg, about 930 ml O2 per min per kg; the row at the minimum climb power reproduces it' },
  verdict: 'cannot-evaluate', missing: ['cardiac output Q and arterial O2 content Ca for a 60 g flying fish (no Exocoetidae physiology sourced); the gill-to-blood link is not formalised'],
  whatWouldEliminate: 'a committed Q * Ca below the O2_needed_climb_ml_per_s of the chosen speed (C14 with climb_rate_m_s = 1), under the named hypotheses: Fick, aerobic (not burst) power, eta = 0.1 from bats, E_O2 = 20.1 J/ml',
  kernel: 'the arithmetic here is plain computation; a kernel certificate is generated by lean/eliminate/eliminate.mjs only when a candidate commits Q and Ca',
  generated: new Date().toISOString()
};
fs.writeFileSync(path.join(here, 'flier-aerobic-requirement.json'), JSON.stringify(out, null, 1));
console.log(JSON.stringify(rows.map(r => ({ v: r.v_m_s, O2_climb_ml_min_kg: r.O2_needed_climb_ml_per_min_per_kg, metabolic_climb_W: r.metabolic_needed_climb_W }))));
