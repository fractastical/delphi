#!/usr/bin/env node
// Developmental-ordering certificate for the fin subtree (genotype/fin-subtree.json): the develops_from edges
// with both stages known must go strictly later in the ZFIN stage series (derivative after precursor); the
// kernel evaluates the checker (Delphi.Genotype.devOrderedB) on the literals. Edges with an unknown stage are
// listed as cannot-evaluate, not passed.
//   node lean/genotype/certify-dev.mjs -> lean/Delphi/Certificates/FinDevelopment.lean, lean/genotype/dev-certificate.json
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const leanDir = path.resolve(here, '..');
const root = path.resolve(here, '../..');
const file = 'genotype/fin-subtree.json';
const F = JSON.parse(fs.readFileSync(path.join(root, file), 'utf8'));
const sha = crypto.createHash('sha256').update(fs.readFileSync(path.join(root, file))).digest('hex');
const nodes = {};
for (const [layer, L] of Object.entries(F.layers)) for (const n of L.nodes) nodes[n.term] = { ...n, layer };
// Stage order: the ZFIN stage series ids (ZFS:00000nn) are assigned in developmental order for the main series;
// the numeric part is used as the stage number, with ZFS:0000000 ("Unknown") meaning no stage.
const zfsNum = n => { const z = n.stage_range && n.stage_range.start_zfs; if (!z) return 0; const m = z.match(/ZFS:(\d+)/); return m ? Number(m[1]) : 0; };
const dev = F.edges.filter(e => /develops_from/.test(e.rel));
const rows = dev.map(e => { const c = nodes[e.child], p = nodes[e.parent]; return { derivative: e.child, derivativeLabel: c?.label, derivativeStage: c?.stage_range?.start, derivativeZfs: zfsNum(c), precursor: e.parent, precursorLabel: p?.label, precursorStage: p?.stage_range?.start, precursorZfs: zfsNum(p) }; });
const evaluable = rows.filter(r => r.derivativeZfs > 0 && r.precursorZfs > 0);
const unknown = rows.filter(r => !(r.derivativeZfs > 0 && r.precursorZfs > 0));
const terms = [...new Set(evaluable.flatMap(r => [r.derivative, r.precursor]))].sort();
const idx = new Map(terms.map((t, i) => [t, i]));
const levels = terms.map(t => zfsNum(nodes[t]));
const edges = evaluable.map(r => [idx.get(r.derivative), idx.get(r.precursor)]).sort((a, b) => a[0] - b[0] || a[1] - b[1]);
const lean = `import Delphi.Genotype
/-!
GENERATED by lean/genotype/certify-dev.mjs from ${file} (sha256 ${sha}, built ${F.built}). Do not edit; regenerate.
Nodes: ${terms.length} ZFA terms of the pectoral-fin subtree that take part in a develops_from edge with both stages known;
level = numeric part of the ZFIN stage id of the term's stage_range.start (${terms.map((t, i) => `${t} ${nodes[t].label} ${levels[i]}`).join('; ')}).
Edges: ${edges.length} develops_from edges (derivative, precursor); ${unknown.length} further edges have an unknown stage and are not certified.
-/

namespace Delphi.Genotype.Certificates

def finDevLevels : List ℕ := [${levels.join(', ')}]
def finDevEdges : List (ℕ × ℕ) := [${edges.map(([a, b]) => `(${a}, ${b})`).join(', ')}]

/-- The develops_from graph of the pectoral-fin subtree (stages known). -/
def finDev : Delphi.Blueprint.Graph ℕ := { nodes := List.range ${terms.length}, root := 0, level := fun i => finDevLevels.getD i 0, partOf := finDevEdges }

/-- The kernel evaluates the checker: every derivative is staged strictly after its precursor. -/
theorem finDev_check : devOrderedB finDev = true := by decide +kernel

/-- **No part of the fin is staged before its precursor, and develops_from is acyclic** (stages known). -/
theorem finDev_ordered : (∀ a b, finDev.Edge a b → finDev.level b < finDev.level a) ∧ finDev.Acyclic :=
  devOrdered_of_check finDev finDev_check

end Delphi.Genotype.Certificates
`;
fs.mkdirSync(path.join(leanDir, 'Delphi/Certificates'), { recursive: true });
fs.writeFileSync(path.join(leanDir, 'Delphi/Certificates/FinDevelopment.lean'), lean);
const candidates = [process.env.ELAN_HOME, path.join(process.env.USERPROFILE || process.env.HOME || '', '.elan'), 'C:/Temp/elan'].filter(Boolean);
let bin = ''; for (const c of candidates) { const d = path.join(c, 'bin'); if (fs.existsSync(path.join(d, process.platform === 'win32' ? 'lake.exe' : 'lake'))) { bin = d; break; } }
const env = { ...process.env, PATH: (bin ? bin + path.delimiter : '') + process.env.PATH }; if (bin && !process.env.ELAN_HOME) env.ELAN_HOME = path.dirname(bin);
const t0 = Date.now();
const r = spawnSync('lake', ['env', 'lean', 'Delphi/Certificates/FinDevelopment.lean'], { cwd: leanDir, env, encoding: 'utf8', shell: process.platform === 'win32', maxBuffer: 64 * 1024 * 1024 });
const out = (r.stdout || '') + (r.stderr || '');
const ok = r.status === 0 && !/error:/.test(out);
const cert = { generated: new Date().toISOString(), tool: 'lean/genotype/certify-dev.mjs', source: { file, sha256: sha, built: F.built }, leanModule: 'lean/Delphi/Certificates/FinDevelopment.lean', theorems: { check: 'Delphi.Genotype.Certificates.finDev_check', ordered: 'Delphi.Genotype.Certificates.finDev_ordered' },
  stageOrder: 'numeric part of the ZFIN stage-series id (ZFS:00000nn) of stage_range.start; ZFS:0000000 (Unknown) is no stage',
  edges: { developsFrom: rows.length, certified: evaluable.length, unknownStage: unknown.length }, certifiedEdges: evaluable, unknownStageEdges: unknown,
  compile: { ok, exit: r.status, seconds: +((Date.now() - t0) / 1000).toFixed(1), tail: out.trim().split(/\r?\n/).slice(-3) },
  kernelChecked: ['Every develops_from edge with both stages known goes strictly later in the ZFIN stage series (derivative after precursor), and the develops_from relation on those nodes is acyclic.'],
  assumed: ['That the ZFIN stage-series ids order the stages (they are assigned in developmental order for the main series).', 'The 4 edges with an unknown stage (scapulocoracoid, mesocoracoid cartilage, pectoral fin radial) are not certified.', 'Nothing about the flying fish: the subtree is zebrafish anatomy (ZFA) joined to the blueprint by cross-references.'] };
fs.writeFileSync(path.join(here, 'dev-certificate.json'), JSON.stringify(cert, null, 1));
console.log(`${terms.length} terms, ${edges.length} certified edges, ${unknown.length} unknown-stage edges; compile ${ok ? 'ok' : 'FAILED'} in ${cert.compile.seconds}s`);
if (!ok) { console.log(out.split(/\r?\n/).slice(0, 15).join('\n')); process.exit(1); }
