// Shared helpers for the worked examples. Each example:
//   1. calls the studio's exported handlers (the same functions server.mjs, cli.mjs and http.mjs call),
//   2. writes everything it got back to output.json next to it,
//   3. writes README.md from those JSON values (so every number quoted there is copied from output.json,
//      with its provenance kind), and
//   4. checks the result against what the README says; any unexpected result exits non-zero, so the
//      example doubles as a regression test.
import fs from 'node:fs';
import path from 'node:path';

export const SIM = path.resolve(import.meta.dirname, '..');

/** Format a number for prose: 4 significant figures (full precision stays in output.json). */
export function n(v, sig = 4) {
  if (v === null || v === undefined) return 'null';
  if (typeof v === 'boolean') return String(v);
  if (typeof v !== 'number') return String(v);
  if (!Number.isFinite(v)) return String(v);
  if (v === 0) return '0';
  return String(Number(v.toPrecision(sig)));
}
/** "value unit (kind)" from a metric record {value, unit, kind}. */
export function q(m, unit) {
  if (!m) return 'missing';
  return `${n(m.value)}${(unit ?? m.unit) && m.value !== null && typeof m.value === 'number' ? ' ' + (unit ?? m.unit) : ''} (${m.kind ?? 'no kind'})`;
}
export const metric = (run, key) => run?.metrics?.find(m => m.key === key) ?? null;

export function checker() {
  const checks = [];
  const expect = (name, cond, detail = '') => { checks.push({ name, pass: !!cond, detail: cond ? '' : String(detail) }); return !!cond; };
  return { checks, expect };
}

/** Write output.json + README.md, print a summary, set the exit code. */
export function finish({ dir, title, output, readme, checks, headline }) {
  const failed = checks.filter(c => !c.pass);
  const meta = { example: path.basename(dir), ran_at: new Date().toISOString(), node: process.version, headline, checks };
  fs.writeFileSync(path.join(dir, 'output.json'), JSON.stringify({ meta, ...output }, null, 1));
  const banner = failed.length
    ? `> **UNEXPECTED RESULT (${failed.length} check${failed.length > 1 ? 's' : ''} failed on the last run, ${meta.ran_at}).** The prose below was written for the expected result; the numbers are the current ones. Failed checks:\n${failed.map(c => `> - ${c.name}${c.detail ? `: ${c.detail}` : ''}`).join('\n')}\n\n`
    : '';
  const checkTable = `\n## Checks this script enforces (exit code 1 if any fails)\n\n| check | last run |\n|---|---|\n${checks.map(c => `| ${c.name.replace(/\|/g, '\|')} | ${c.pass ? 'pass' : 'FAIL' + (c.detail ? ': ' + c.detail.replace(/\|/g, '\|') : '')} |`).join('\n')}\n`;
  const footer = `\n---\nGenerated by \`node sim-engine/examples/${path.basename(dir)}/run.mjs\` on ${meta.ran_at} from \`output.json\` in this folder. ` +
    'Numbers are rounded to 4 significant figures; full precision and every provenance record are in output.json. ' +
    'Provenance kinds: measured, measured-secondhand, borrowed, derived, calibrated (tuned to reproduce one observation: never a result), assumed (a placeholder). ' +
    'Lean verdicts are floating-point evaluations of Lean-backed formulas, not kernel proofs. No Aves data used.\n';
  fs.writeFileSync(path.join(dir, 'README.md'), `# ${title}\n\n${banner}${readme.trim()}\n${checkTable}${footer}`);
  console.log(`${path.basename(dir)}: ${headline}`);
  for (const c of checks) console.log(`  ${c.pass ? 'ok  ' : 'FAIL'} ${c.name}${c.pass ? '' : '  -- ' + c.detail}`);
  process.exitCode = failed.length ? 1 : 0;
}

/** Strip the bulky parts of an envelope for output.json while keeping provenance and scope. */
export function slim(env, { keepTrace = false } = {}) {
  const e = structuredClone(env);
  const walk = o => { if (!o || typeof o !== 'object') return; if (!keepTrace && 'trace' in o) o.trace = `[${Array.isArray(o.trace) ? o.trace.length : '?'} entries omitted]`; for (const v of Object.values(o)) walk(v); };
  walk(e);
  return e;
}

/** Markdown table helper. */
export const table = (head, rows) => `| ${head.join(' | ')} |\n|${head.map(() => '---').join('|')}|\n${rows.map(r => `| ${r.map(x => String(x ?? '').replace(/\|/g, '\|').replace(/\n/g, ' ')).join(' | ')} |`).join('\n')}`;

// Crash guard: if an example throws (for example because a studio module is mid-edit), its README and
// output.json are overwritten with the failure rather than left showing the previous run as if current.
const entry = process.argv[1] ? path.dirname(path.resolve(process.argv[1])) : null;
if (entry && path.dirname(entry) === import.meta.dirname) {
  const onCrash = e => {
    const at = new Date().toISOString();
    try {
      fs.writeFileSync(path.join(entry, 'output.json'), JSON.stringify({ meta: { example: path.basename(entry), ran_at: at, node: process.version, headline: `CRASHED: ${e?.message}`, checks: [{ name: 'script completed without an exception', pass: false, detail: e?.message }] }, error: String(e?.stack || e) }, null, 1));
      fs.writeFileSync(path.join(entry, 'README.md'), `# ${path.basename(entry)}\n\n> **The last run (${at}) crashed before producing a result.** This is kept, not worked around: it is a studio failure, reported to the hub.\n\n\`\`\`\n${String(e?.stack || e).slice(0, 3000)}\n\`\`\`\n\nRe-run with \`node sim-engine/examples/${path.basename(entry)}/run.mjs\`.\n`);
    } catch {}
    console.log(`${path.basename(entry)}: CRASHED: ${e?.message}`);
    process.exitCode = 1;
  };
  process.on('uncaughtException', onCrash);
  process.on('unhandledRejection', onCrash);
}
