#!/usr/bin/env node
// Static mirror of the Lean law API, for the browser and anyone without a server.
//
//   node dashboard/build-lean-api.mjs           write dashboard/public/api/lean/
//   node dashboard/build-lean-api.mjs --check   exit 1 if the mirror on disk differs from what would be written
//
// Writes, from the SAME loader the MCP tools use (lib/lean-source.mjs):
//   api/lean/index.json              every law (summary), every lawset version, the source fingerprint
//   api/lean/laws/<law_id>.json      lean_law_get's result for that law
//   api/lean/lawsets/<version>.json  lean_lawset_get's result for that release
//   api/lean/current.json            the current lawset
//   api/lean/scope.mjs               copy of lib/lean-scope.mjs (the out-of-scope rule) for lean-client.js
// The site's Cloudflare static hosting (dashboard/wrangler.jsonc, assets ./public) then serves GET /api/lean/...
// with no server.
//
// RULE for the Design Studio and every page: fetch laws from the API (the live sim-engine HTTP bridge if one
// is configured, else this /api/lean/ mirror) through dashboard/public/blueprint3d/lean-client.js. Never paste
// a law list into a page. lean/registry/check-exposed.mjs fails when this mirror is stale.
//
// Output is deterministic (no timestamps, no git commit beyond what the registry itself pins), so rebuilding
// unchanged sources leaves the files byte-identical and --check is meaningful.

import fs from 'node:fs';
import path from 'node:path';
import * as src from '../lib/lean-source.mjs';

export const OUT = path.join(import.meta.dirname, 'public', 'api', 'lean');

const SCOPE =
  'Static mirror generated by dashboard/build-lean-api.mjs from lib/lean-source.mjs, the same loader the MCP ' +
  'tools (lean_laws_list, lean_law_get, lean_lawset_get) use. A law\'s status is a registry decision, not a truth ' +
  'value; "proved" means a Lean kernel proof about a model, never that the model describes an organism. Laws ' +
  'absent here are unchecked, not satisfied. Evaluation (lean_check) is not mirrored: the browser runs ' +
  'blueprint3d/browser-check.mjs locally via lean-client.js.';

const safe = id => String(id).replace(/[^A-Za-z0-9._-]/g, '_');

// Strip values that change with the checkout rather than with the laws (fallback mode stamps HEAD).
function stable(o) {
  return JSON.parse(JSON.stringify(o, (k, v) => (k === 'module_hash' ? undefined : v)));
}

export function generate() {
  const reg = src.load({ fresh: true });
  const fp = src.sourceFingerprint();
  const files = {};
  const put = (rel, obj) => { files[rel] = JSON.stringify(obj, null, 1) + '\n'; };
  const list = src.listLaws({});
  put('index.json', {
    api: 'delphisci lean laws, static mirror',
    version: 1,
    origin: reg.origin,
    current_lawset: reg.current,
    lawsets: reg.lawsets.map(s => s.version),
    count: list.count,
    laws: list.laws.map(l => ({ ...l, href: `laws/${safe(l.law_id)}.json` })),
    endpoints: { law: 'laws/<law_id>.json', lawset: 'lawsets/<version>.json', current: 'current.json' },
    scope: SCOPE,
    source_fingerprint: fp,
  });
  for (const l of reg.laws) put(`laws/${safe(l.law_id)}.json`, stable({ ...src.getLaw(l.law_id), scope_note: SCOPE }));
  for (const s of reg.lawsets) put(`lawsets/${safe(s.version)}.json`, src.getLawset(s.version));
  put('current.json', src.getLawset('current'));
  // The scope rule, verbatim, so the browser client computes 'out-of-scope' with the same code as lean_check.
  files['scope.mjs'] = '// GENERATED by dashboard/build-lean-api.mjs: a verbatim copy of lib/lean-scope.mjs. Do not edit.\n' +
    fs.readFileSync(path.join(src.ROOT, 'lib', 'lean-scope.mjs'), 'utf8').replace(/\r\n/g, '\n');
  return files;
}

function onDisk() {
  const out = {};
  const walk = d => { if (!fs.existsSync(d)) return; for (const e of fs.readdirSync(d, { withFileTypes: true })) {
    const p = path.join(d, e.name); if (e.isDirectory()) walk(p); else out[path.relative(OUT, p).replace(/\\/g, '/')] = fs.readFileSync(p, 'utf8'); } };
  walk(OUT);
  return out;
}

// Differences between the mirror on disk and a fresh generation: [{file, why}].
export function diff() {
  const want = generate(), have = onDisk();
  const d = [];
  for (const f of Object.keys(want)) if (have[f] === undefined) d.push({ file: f, why: 'missing' }); else if (have[f].replace(/\r\n/g, '\n') !== want[f]) d.push({ file: f, why: 'stale' });
  for (const f of Object.keys(have)) if (want[f] === undefined) d.push({ file: f, why: 'orphan (no such law/lawset any more)' });
  return d;
}

export function write() {
  const want = generate();
  const have = onDisk();
  for (const f of Object.keys(have)) if (want[f] === undefined) fs.rmSync(path.join(OUT, f));
  for (const [f, text] of Object.entries(want)) {
    const p = path.join(OUT, f);
    fs.mkdirSync(path.dirname(p), { recursive: true });
    if (have[f] !== text) fs.writeFileSync(p, text);
  }
  return Object.keys(want).length;
}

if (import.meta.url === `file:///${process.argv[1]?.replace(/\\/g, '/')}` || import.meta.url === `file://${process.argv[1]}`) {
  if (process.argv.includes('--check')) {
    const d = diff();
    if (d.length) { console.error(`static mirror dashboard/public/api/lean/ is stale (${d.length} files):`); for (const x of d.slice(0, 20)) console.error(`  ${x.why}: ${x.file}`); console.error('fix: node dashboard/build-lean-api.mjs'); process.exit(1); }
    console.log('static mirror up to date');
  } else {
    const n = write();
    console.log(`wrote ${n} files to ${path.relative(process.cwd(), OUT) || OUT}`);
  }
}
