#!/usr/bin/env node
// Copies the pure-ESM Design Studio engine into the static site so the browser runs the IDENTICAL code
// the MCP server runs:
//
//   node dashboard/build-engine.mjs
//
//   sim-engine/lib/<pure>.mjs      -> dashboard/public/blueprint3d/engine/lib/       (organism, state, envelope, ...)
//   sim-engine/scenarios/*.mjs     -> dashboard/public/blueprint3d/engine/scenarios/ (+ manifest.json listing them)
//   bundle (lib/data-node.mjs)     -> dashboard/public/blueprint3d/engine/data/bundle.json
//
// A file is copied only if it has no node-only import (node:*, fs, path, child_process); anything skipped
// is printed with the reason, so a scenario that cannot run in the browser is visible, not silently absent.
// The directory layout mirrors sim-engine/, so relative imports inside the copied files resolve unchanged.
// Lean laws are NOT copied here: the browser reads them from the law registry's own static mirror.
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const ROOT = path.resolve(import.meta.dirname, '..');
const SRC = path.join(ROOT, 'sim-engine');
const OUT = path.join(ROOT, 'dashboard', 'public', 'blueprint3d', 'engine');
const NODE_ONLY = /^\s*import\s[^;]*?from\s+['"](node:[^'"]+|fs|path|os|child_process|url|crypto)['"]/m;
// scenarios/index.mjs is allowed: its node branch is a dynamic import inside a runtime check.

const copied = [], skipped = [];
const REL = /(?:import|export)\s[^;]*?from\s+['"](\.{1,2}\/[^'"]+)['"]/g;
// Pure = no node-only import in the file AND every relative import is itself pure and inside sim-engine/.
// lib/partedit-link.mjs re-exports dashboard/public/blueprint3d/partedit.js (pure, already served by the site);
// the browser copy points at the same file relative to engine/lib/.
const LINK = path.join(SRC, 'lib', 'partedit-link.mjs');
const LINK_BROWSER = [
  '// GENERATED by dashboard/build-engine.mjs: browser twin of sim-engine/lib/partedit-link.mjs.',
  "export { resolveTarget, editableParams, metresPerUnit } from '../../partedit.js';", ''].join('\n');
function impurity(abs, seen = new Set()) {
  if (abs === LINK) return null;
  if (seen.has(abs)) return null; seen.add(abs);
  if (!abs.startsWith(SRC + path.sep)) return `imports ${path.relative(ROOT, abs)}, outside sim-engine/`;
  if (!fs.existsSync(abs)) return `imports missing ${path.relative(ROOT, abs)}`;
  const text = fs.readFileSync(abs, 'utf8');
  if (NODE_ONLY.test(text)) return `static node-only import in ${path.relative(ROOT, abs)}`;
  for (const m of text.matchAll(REL)) { const why = impurity(path.resolve(path.dirname(abs), m[1]), seen); if (why) return why; }
  return null;
}
function copyPure(rel) {
  const src = path.join(SRC, rel);
  const text = fs.readFileSync(src, 'utf8');
  const why = impurity(src);
  if (why) { skipped.push({ file: rel, why }); return false; }
  const dst = path.join(OUT, rel);
  fs.mkdirSync(path.dirname(dst), { recursive: true });
  fs.writeFileSync(dst, src === LINK ? LINK_BROWSER : text);
  copied.push(rel);
  return true;
}

fs.mkdirSync(OUT, { recursive: true });
for (const f of fs.readdirSync(path.join(SRC, 'lib')).filter(f => f.endsWith('.mjs'))) copyPure(`lib/${f}`);
const scen = [];
for (const f of fs.readdirSync(path.join(SRC, 'scenarios')).filter(f => f.endsWith('.mjs')).sort()) {
  if (copyPure(`scenarios/${f}`) && f !== 'index.mjs') scen.push(f);
}
fs.writeFileSync(path.join(OUT, 'scenarios', 'manifest.json'), JSON.stringify({ built: new Date().toISOString(), files: scen }, null, 1));

// Check every relative import of the copied files resolves inside engine/ (else the browser would 404).
const missing = [];
for (const rel of copied) {
  const text = fs.readFileSync(path.join(OUT, rel), 'utf8');
  for (const m of text.matchAll(/(?:import|export)\s[^;]*?from\s+['"](\.{1,2}\/[^'"]+)['"]/g)) {
    const target = path.resolve(path.dirname(path.join(OUT, rel)), m[1]);
    if (!fs.existsSync(target)) missing.push(`${rel} -> ${m[1]}`);
  }
}

const { loadBundle } = await import(pathToFileURL(path.join(SRC, 'lib', 'data-node.mjs')).href);
const bundle = await loadBundle();
fs.mkdirSync(path.join(OUT, 'data'), { recursive: true });
fs.writeFileSync(path.join(OUT, 'data', 'bundle.json'), JSON.stringify(bundle));

console.log(JSON.stringify({ out: path.relative(ROOT, OUT).replace(/\\/g, '/'), copied, skipped, scenarios: scen,
  unresolved_imports: missing, bundle_bytes: fs.statSync(path.join(OUT, 'data', 'bundle.json')).size }, null, 1));
if (missing.length) process.exitCode = 1;
