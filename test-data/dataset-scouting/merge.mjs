#!/usr/bin/env node
// Merge every scouting record into merged/scouting.json and COVERAGE.md: which untested claims have
// their data located, which have gaps, and how often the assessors' dataset guesses held up.
//
//   node test-data/dataset-scouting/merge.mjs
//
// No dependencies (Node 20+).

import { mkdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";
import { ROOT, STATUSES, DS_VERDICTS, listRecords, validateRecord } from "./validate.mjs";

const claimsPath = join(ROOT, "../../docs/claims.json");
const byId = existsSync(claimsPath) ? Object.fromEntries(JSON.parse(readFileSync(claimsPath, "utf8")).claims.map(c => [c.id, c])) : {};

const records = [];
let invalid = 0;
for (const dir of listRecords()) {
  const r = validateRecord(dir);
  if (r.errors.length || !r.record) { invalid++; continue; }
  records.push(r.record);
}

const count = (xs, f) => xs.filter(f).length;
const pct = (a, b) => (b ? `${Math.round((100 * a) / b)}%` : "·");

const claims = records.map(d => ({
  id: d.claim_id, project: d.project, thinker: byId[d.claim_id]?.thinker ?? null, label: byId[d.claim_id]?.label ?? null,
  testability: byId[d.claim_id]?.testability ?? null, status: d.status, scouted_at: d.scouted_at, scout: d.scout,
  variables_needed: d.variables_needed,
  datasets: d.datasets.map(x => ({ id: x.id, name: x.name, landing_url: x.landing_url, access_url: x.access_url ?? null, doi: x.doi ?? null,
    license: x.license ?? null, verdict: x.verdict, suggested_by: x.suggested_by, http_status: x.checked?.http_status ?? null,
    variables_present: x.variables_present ?? [], reuses_organism_dataset: x.reuses_organism_dataset ?? null })),
  summary: d.summary, next_step: d.next_step ?? null,
})).sort((a, b) => STATUSES.indexOf(a.status) - STATUSES.indexOf(b.status) || (b.testability ?? 0) - (a.testability ?? 0));

// Assessor hit rate: of datasets an assessor named, how many held or partly held once checked.
const assessors = {};
const allDs = records.flatMap(d => d.datasets);
for (const x of allDs) for (const a of x.suggested_by ?? []) {
  assessors[a] ??= Object.fromEntries(DS_VERDICTS.map(v => [v, 0]));
  assessors[a][x.verdict]++;
}
const found = allDs.filter(x => !(x.suggested_by ?? []).length);

// Datasets that hold across claims: the reusable core.
const reusable = {};
for (const d of records) for (const x of d.datasets) if (["holds", "partial"].includes(x.verdict)) {
  reusable[x.id] ??= { id: x.id, name: x.name, landing_url: x.landing_url, claims: [], holds: 0, partial: 0 };
  reusable[x.id].claims.push(d.claim_id); reusable[x.id][x.verdict]++;
}
const core = Object.values(reusable).sort((a, b) => b.claims.length - a.claims.length);

const byProject = {};
for (const c of claims) { byProject[c.project] ??= Object.fromEntries(STATUSES.map(s => [s, 0])); byProject[c.project][c.status]++; }

const summary = {
  generated: new Date().toISOString().slice(0, 19) + "Z", scouted: claims.length, invalid_records: invalid,
  by_status: Object.fromEntries(STATUSES.map(s => [s, count(claims, c => c.status === s)])),
  by_project: byProject,
  datasets_checked: allDs.length, datasets_by_verdict: Object.fromEntries(DS_VERDICTS.map(v => [v, count(allDs, x => x.verdict === v)])),
  assessor_suggestions: assessors, scout_found: Object.fromEntries(DS_VERDICTS.map(v => [v, count(found, x => x.verdict === v)])),
};

mkdirSync(join(ROOT, "merged"), { recursive: true });
writeFileSync(join(ROOT, "merged/scouting.json"), JSON.stringify({ ...summary, reusable: core, claims }, null, 2) + "\n");

const gh = "https://github.com/fractastical/delphi/blob/main/test-data/dataset-scouting";
const md = [
  "# Dataset scouting: coverage",
  "",
  `Generated by \`node test-data/dataset-scouting/merge.mjs\` on ${summary.generated.replace("T", " ").slice(0, 16)} UTC. Do not edit by hand.`,
  "",
  `**${claims.length} untested claims scouted**: ${STATUSES.map(s => `${summary.by_status[s]} ${s}`).join(", ")}. ` +
    `${allDs.length} datasets checked against live sources (${DS_VERDICTS.map(v => `${summary.datasets_by_verdict[v]} ${v}`).join(", ")}); ` +
    `${found.length} of them found by scouts rather than named by assessors.` + (invalid ? ` ${invalid} records failed validation and are excluded.` : ""),
  "",
  "A scouting record says where the data are, not what they show. `data-ready` means at least one open dataset holds every variable the claim's test needs; the test itself is still to be pre-registered in `test-data/claim-tests/`.",
  "",
  "## By project",
  "",
  `| Project | scouted | ${STATUSES.join(" | ")} |`, `|---|---:|${"---:|".repeat(STATUSES.length)}`,
  ...Object.entries(byProject).map(([p, s]) => `| ${p} | ${STATUSES.reduce((n, k) => n + s[k], 0)} | ${STATUSES.map(k => s[k] || "·").join(" | ")} |`),
  "",
  "## Did the assessors' dataset guesses hold up?",
  "",
  "Each dataset-resolvability assessment names candidate datasets. Once a scout checked them:",
  "",
  `| Named by | checked | holds | partial | rejected | unreachable | not-found | holds or partial |`, `|---|---:|---:|---:|---:|---:|---:|---:|`,
  ...Object.entries(assessors).map(([a, v]) => { const n = DS_VERDICTS.reduce((s, k) => s + v[k], 0); return `| ${a} | ${n} | ${DS_VERDICTS.map(k => v[k] || "·").join(" | ")} | ${pct(v.holds + v.partial, n)} |`; }),
  (() => { const v = summary.scout_found; const n = found.length; return `| scout (new) | ${n} | ${DS_VERDICTS.map(k => v[k] || "·").join(" | ")} | ${pct(v.holds + v.partial, n)} |`; })(),
  "",
  "## Datasets that serve several claims",
  "",
  "| Dataset | claims | holds | partial |", "|---|---:|---:|---:|",
  ...core.slice(0, 30).map(x => `| [${x.name}](${x.landing_url}) | ${x.claims.length} | ${x.holds || "·"} | ${x.partial || "·"} |`),
  "",
  "## Every scouted claim",
  "",
  "| Claim | status | testability | holds | partial | summary |", "|---|---|---:|---:|---:|---|",
  ...claims.map(c => `| [\`${c.id}\`](${gh}/${c.project}/${c.id}/datasets.json) | ${c.status} | ${c.testability ?? "·"} | ${count(c.datasets, x => x.verdict === "holds") || "·"} | ${count(c.datasets, x => x.verdict === "partial") || "·"} | ${String(c.summary).replace(/\|/g, "\\|").slice(0, 180)} |`),
  "",
].join("\n");
writeFileSync(join(ROOT, "COVERAGE.md"), md);
console.log(`${claims.length} records merged (${invalid} invalid skipped) -> merged/scouting.json, COVERAGE.md`);
console.log(STATUSES.map(s => `${s} ${summary.by_status[s]}`).join(", "));
